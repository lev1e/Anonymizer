def _countries() -> tuple[dict[str, str], dict[str, str]]:
    names: dict[str, str] = {}
    adjectives: dict[str, str] = {}
    for line in _COUNTRY_TABLE.strip().splitlines():
        forms, _, adjs = line.partition("|")
        spelled = [f.strip() for f in forms.split(";") if f.strip()]
        key = fold(spelled[0])
        for form in spelled:
            names[form] = key
        for adj in adjs.split(","):
            if adj.strip():
                adjectives[fold(adj.strip())] = key
    return names, adjectives


